#!/usr/bin/env python3
"""codex_setup.py -- check and prepare an OpenAI Codex install for the gismo plugin.

Usage: codex_setup.py check     [--codex-home DIR] [--project DIR]
       codex_setup.py install   [--codex-home DIR] [--tier TIER=MODEL]...
       codex_setup.py set-depth [--codex-home DIR] [--depth N]

Codex installs this plugin's skills, scripts and hook, but a Codex plugin cannot ship
subagents: Codex reads agent roles only from ``$CODEX_HOME/agents/`` and a trusted
project's ``.codex/agents/``. ``install`` converts every ``agents/*.md`` of the plugin into
a role file ``$CODEX_HOME/agents/gismo-<name>.toml`` whose role name is ``gismo:<name>``,
the name the skills and agent prompts already dispatch by.

A role file is parsed with unknown keys denied, so it carries only ``name``,
``description``, ``developer_instructions``, ``model`` and ``model_reasoning_effort``. The
Claude ``model:`` tier (haiku, sonnet, opus) maps to a Codex model through the tier map;
``--tier`` overrides one entry, and the map in use is kept in
``$CODEX_HOME/gismo-codex-setup.json`` so a later ``install`` or ``check`` reuses it.
``${CLAUDE_PLUGIN_ROOT}`` in an agent body is replaced by the plugin's absolute root,
which Codex does not expand in prompt text.

``check`` is read-only. It reports the Codex version, ``agents.max_depth`` (the framework
nests three levels deep; Codex defaults to 1), whether ``multi_agent`` is disabled,
whether the installed role files match what ``install`` would write now, and whether the
mapped models and efforts exist in Codex's model catalog.

``set-depth`` writes ``[agents] max_depth`` into ``$CODEX_HOME/config.toml`` after copying
the file to ``config.toml.bak-gismo-<UTC timestamp>``. It refuses when ``agents`` is
defined in a form it cannot edit as text (a dotted key or an inline table).

Output: one line per finding, ``OK|WARN|FAIL|INFO <item>: <message>``, then
``STATUS: OK`` or ``STATUS: FAIL <n>``. Exit: 0 OK, 1 a check failed, 2 usage or I/O error.
"""

import argparse
import datetime
import json
import os
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

PLUGIN_ROOT = Path(__file__).resolve().parents[3]
REQUIRED_DEPTH = 3
CODEX_DEFAULT_DEPTH = 1
TESTED_CODEX = (0, 154, 0)
DEFAULT_TIERS = {"haiku": "gpt-5.6-luna", "sonnet": "gpt-5.6-terra", "opus": "gpt-5.6-sol"}
STATE_FILE = "gismo-codex-setup.json"
MARKER = "# Generated by gismo codex-setup"
ROLE_PREFIX = "gismo"

PREAMBLE = """\
## Running under OpenAI Codex

This role was generated by `gismo:codex-setup` from the gismo plugin's Claude Code agent
`{stem}`. The instructions below were written for Claude Code; read them with these
substitutions:

- Dispatching a `gismo:<name>` agent "via the Agent tool" means calling `spawn_agent` with
  `agent_type` set to `gismo:<name>`. Never pass `model` or `reasoning_effort`: the role
  file fixes both.
- `SendMessage` to a running agent means Codex's tool for messaging a running agent; wait
  for a dispatched agent with `wait_agent`.
- Read, Grep and Glob are shell commands here; Edit and Write are file edits.
- TaskCreate, TaskUpdate and ListAgents do not exist in Codex. Skip the steps that use them,
  as the protocol allows when the native task list is unavailable.
- Paths under the plugin root were resolved at install time to `{root}`.

Your Claude Code definition grants only these tools: {tools}. Codex does not enforce that
list, so keep to it yourself{limits}.
"""


class SetupError(Exception):
    """A problem the user must resolve; reported as ``STATUS: FAIL`` with exit 2."""


# --- agent conversion -------------------------------------------------------------------


def _unquote(value):
    """Scalar value of a single-line YAML frontmatter entry (plain, '...' or "...")."""
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] == "'":
        return value[1:-1].replace("''", "'")
    if len(value) >= 2 and value[0] == value[-1] == '"':
        escapes = {"n": "\n", "t": "\t", '"': '"', "\\": "\\", "/": "/"}
        return re.sub(r"\\(.)", lambda m: escapes.get(m.group(1), m.group(0)), value[1:-1])
    return value


def parse_agent(text):
    """Split an agent file into its frontmatter fields and its body."""
    match = re.match(r"---\n(.*?)\n---\n?(.*)", text, re.S)
    if not match:
        raise SetupError("agent file has no frontmatter")
    fields = {}
    for line in match.group(1).splitlines():
        key, sep, value = line.partition(":")
        if sep and re.fullmatch(r"[a-z][a-z-]*", key):
            fields[key] = _unquote(value)
    return fields, match.group(2)


def _toml_escape(text, multiline):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n" and multiline:
            out.append("\n")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append(f"\\u{ord(ch):04X}")
        else:
            out.append(ch)
    return "".join(out)


def toml_string(text):
    return '"' + _toml_escape(text, multiline=False) + '"'


def toml_multiline(text):
    # The newline after the opening quotes is trimmed by TOML.
    return '"""\n' + _toml_escape(text, multiline=True) + '"""'


def _limits(tools):
    limits = []
    if "Edit" not in tools and "Write" not in tools:
        limits.append("do not create or modify files")
    if "Agent" not in tools:
        limits.append("do not spawn agents")
    if "Bash" not in tools:
        limits.append("use the shell only to read and search files")
    return (": " + "; ".join(limits)) if limits else ""


def convert_agent(path, tiers, root, version):
    """Codex role file text for one Claude agent file, and the role's model and effort."""
    fields, body = parse_agent(path.read_text(encoding="utf-8"))
    stem = fields.get("name") or path.stem
    tools = [t.strip() for t in fields.get("tools", "").split(",") if t.strip()]
    preamble = PREAMBLE.format(
        stem=stem,
        root=root,
        tools=", ".join(tools) if tools else "(not restricted)",
        limits=_limits(tools) if tools else "",
    )
    instructions = preamble + "\n" + body.strip("\n").replace("${CLAUDE_PLUGIN_ROOT}", str(root)) + "\n"
    if not fields.get("description", "").strip():
        raise SetupError(f"{path.name}: empty description (Codex rejects the role)")

    model = tiers.get(fields.get("model", ""))
    effort = fields.get("effort")
    lines = [
        f"{MARKER} from {path.name} (plugin {version}).",
        "# Do not edit: rerun gismo:codex-setup install after updating the plugin.",
        f"name = {toml_string(f'{ROLE_PREFIX}:{stem}')}",
        f"description = {toml_string(fields['description'])}",
    ]
    if model:
        lines.append(f"model = {toml_string(model)}")
    if effort:
        lines.append(f"model_reasoning_effort = {toml_string(effort)}")
    lines.append(f"developer_instructions = {toml_multiline(instructions)}")
    return "\n".join(lines) + "\n", {"tier": fields.get("model"), "model": model, "effort": effort}


def plugin_version(root):
    try:
        return json.loads((root / ".claude-plugin" / "plugin.json").read_text())["version"]
    except (OSError, ValueError, KeyError):
        return "unknown"


def expected_roles(root, tiers):
    """``{filename: (text, info)}`` for every agent the plugin ships."""
    version = plugin_version(root)
    roles = {}
    for path in sorted((root / "agents").glob("*.md")):
        text, info = convert_agent(path, tiers, root, version)
        roles[f"{ROLE_PREFIX}-{path.stem}.toml"] = (text, info)
    if not roles:
        raise SetupError(f"no agents found under {root / 'agents'}")
    return roles


# --- Codex home, state and config --------------------------------------------------------


def codex_home(arg):
    if arg:
        return Path(arg).expanduser()
    env = os.environ.get("CODEX_HOME")
    return Path(env).expanduser() if env else Path.home() / ".codex"


def load_toml(path):
    if not path.is_file():
        return {}
    try:
        return tomllib.loads(path.read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as error:
        raise SetupError(f"{path}: not valid TOML ({error})")


def load_state(home):
    try:
        return json.loads((home / STATE_FILE).read_text())
    except (OSError, ValueError):
        return {}


def resolve_tiers(home, overrides):
    tiers = dict(DEFAULT_TIERS)
    tiers.update(load_state(home).get("tiers", {}))
    for item in overrides or []:
        tier, sep, model = item.partition("=")
        if not sep or tier not in DEFAULT_TIERS or not model.strip():
            raise SetupError(f"--tier expects one of {', '.join(DEFAULT_TIERS)}=<model>, got '{item}'")
        tiers[tier] = model.strip()
    return tiers


def max_depth(config):
    agents = config.get("agents")
    if isinstance(agents, dict) and isinstance(agents.get("max_depth"), int):
        return agents["max_depth"]
    return None


def set_max_depth_text(text, depth):
    """``text`` with ``[agents] max_depth = depth``; raises SetupError when it cannot edit."""
    lines = text.splitlines(keepends=True)
    header = next((i for i, line in enumerate(lines)
                   if re.match(r"\s*\[\s*agents\s*\]\s*(#.*)?$", line)), None)
    if header is not None:
        end = next((i for i in range(header + 1, len(lines))
                    if re.match(r"\s*\[", lines[i])), len(lines))
        for i in range(header + 1, end):
            if re.match(r"\s*max_depth\s*=", lines[i]):
                lines[i] = f"max_depth = {depth}\n"
                break
        else:
            lines.insert(header + 1, f"max_depth = {depth}\n")
        new = "".join(lines)
    else:
        sep = "" if not text or text.endswith("\n") else "\n"
        new = text + sep + ("\n" if text.strip() else "") + f"[agents]\nmax_depth = {depth}\n"
    try:
        parsed = tomllib.loads(new)
    except tomllib.TOMLDecodeError:
        parsed = None
    if parsed is None or max_depth(parsed) != depth:
        raise SetupError("config.toml defines `agents` as a dotted key or inline table; "
                         f"set agents.max_depth = {depth} by hand")
    return new


# --- Codex CLI probes ---------------------------------------------------------------------


def _run_codex(*args, home=None):
    exe = shutil.which("codex")
    if not exe:
        return None
    env = {**os.environ, "CODEX_HOME": str(home)} if home else None
    try:
        result = subprocess.run([exe, *args], capture_output=True, text=True, timeout=60, env=env)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return result.stdout if result.returncode == 0 else None


def codex_version():
    out = _run_codex("--version") or ""
    match = re.search(r"(\d+)\.(\d+)\.(\d+)", out)
    return tuple(int(g) for g in match.groups()) if match else None


def model_catalog(home):
    """``{slug: set(efforts)}`` from ``codex debug models``, or None when unavailable.

    The catalog depends on the account logged in under ``home``.
    """
    out = _run_codex("debug", "models", home=home)
    if not out:
        return None
    try:
        data = json.loads(out)
    except ValueError:
        return None
    models = data.get("models", []) if isinstance(data, dict) else data
    return {
        m.get("slug"): {lvl.get("effort") for lvl in m.get("supported_reasoning_levels", [])}
        for m in models if isinstance(m, dict) and m.get("slug")
    }


# --- commands ---------------------------------------------------------------------------


class Report:
    def __init__(self):
        self.failures = 0

    def __call__(self, level, item, message):
        if level == "FAIL":
            self.failures += 1
        print(f"{level} {item}: {message}")

    def finish(self):
        print("STATUS: OK" if not self.failures else f"STATUS: FAIL {self.failures}")
        return 0 if not self.failures else 1


def cmd_check(args):
    home = codex_home(args.codex_home)
    report = Report()
    report("INFO", "plugin", f"{PLUGIN_ROOT} (version {plugin_version(PLUGIN_ROOT)})")
    report("INFO", "codex-home", str(home))

    found = codex_version()
    if found is None:
        report("WARN", "codex", "`codex --version` did not run; is Codex on PATH?")
    elif found < TESTED_CODEX:
        report("WARN", "codex", f"version {'.'.join(map(str, found))} is older than the tested "
                                f"{'.'.join(map(str, TESTED_CODEX))}")
    else:
        report("OK", "codex", f"version {'.'.join(map(str, found))}")

    config = load_toml(home / "config.toml")
    features = config.get("features", {}) if isinstance(config.get("features"), dict) else {}
    if features.get("multi_agent") is False:
        report("FAIL", "multi_agent", "features.multi_agent = false in config.toml; subagents are off")
    if features.get("multi_agent_v2") is True:
        report("INFO", "multi_agent_v2", "enabled; Codex ignores agents.max_depth in this mode")

    depth, source = max_depth(config), "config.toml"
    if args.project:
        project_config = load_toml(Path(args.project) / ".codex" / "config.toml")
        if max_depth(project_config) is not None:
            depth, source = max_depth(project_config), f"{args.project}/.codex/config.toml (trusted projects only)"
    if depth is None:
        depth, source = CODEX_DEFAULT_DEPTH, "Codex default"
    if depth >= REQUIRED_DEPTH:
        report("OK", "max_depth", f"{depth} from {source}")
    else:
        report("FAIL", "max_depth", f"{depth} from {source}; the task loop nests {REQUIRED_DEPTH} deep "
                                    "(orchestrator > task-lead > implementer > scout). Fix: set-depth")

    tiers = resolve_tiers(home, None)
    roles = expected_roles(PLUGIN_ROOT, tiers)
    agents_dir = home / "agents"
    missing, stale, links = [], [], []
    for filename, (text, _) in roles.items():
        path = agents_dir / filename
        if path.is_symlink():
            links.append(filename)
        elif not path.is_file():
            missing.append(filename)
        elif path.read_text(encoding="utf-8") != text:
            stale.append(filename)
    orphans = [p.name for p in sorted(agents_dir.glob(f"{ROLE_PREFIX}-*.toml"))
               if p.name not in roles and _is_generated(p)]
    if not (missing or stale or links or orphans):
        report("OK", "agents", f"{len(roles)} roles installed in {agents_dir} and current")
    for label, names in (("missing", missing), ("out of date", stale),
                         ("symlinked (Codex rejects symlinked role files)", links),
                         ("no longer shipped", orphans)):
        if names:
            report("FAIL", "agents", f"{label}: {', '.join(names)}. Fix: install")

    catalog = model_catalog(home)
    if catalog is None:
        report("WARN", "models", "could not read `codex debug models`; tier map not validated")
    else:
        for filename, (_, info) in roles.items():
            if not info["model"]:
                report("WARN", "models", f"{filename}: tier '{info['tier']}' has no mapping; "
                                         "the role inherits the caller's model")
            elif info["model"] not in catalog:
                report("FAIL", "models", f"{filename}: model '{info['model']}' is not in this account's "
                                         f"Codex catalog ({', '.join(sorted(catalog))}). "
                                         f"Fix: install --tier {info['tier']}=<model>")
            elif info["effort"] and info["effort"] not in catalog[info["model"]]:
                report("FAIL", "models", f"{filename}: {info['model']} does not support effort '{info['effort']}'")
    report("INFO", "tiers", ", ".join(f"{t}={m}" for t, m in tiers.items()))

    report("INFO", "hook", "the tier guard runs only after it is approved in Codex's /hooks")
    return report.finish()


def _is_generated(path):
    try:
        with open(path, encoding="utf-8") as handle:
            return handle.readline().startswith(MARKER)
    except OSError:
        return False


def cmd_install(args):
    home = codex_home(args.codex_home)
    tiers = resolve_tiers(home, args.tier)
    roles = expected_roles(PLUGIN_ROOT, tiers)
    agents_dir = home / "agents"
    agents_dir.mkdir(parents=True, exist_ok=True)
    report = Report()

    for filename, (text, info) in roles.items():
        path = agents_dir / filename
        if path.exists() and not path.is_symlink() and not _is_generated(path):
            report("FAIL", "agents", f"{path} exists and was not written by codex-setup; left untouched")
            continue
        if path.is_symlink():
            path.unlink()
        path.write_text(text, encoding="utf-8")
        report("OK", "agents", f"{filename}: {info['tier']} -> {info['model'] or 'caller model'}"
                               f"{', effort ' + info['effort'] if info['effort'] else ''}")
    for path in sorted(agents_dir.glob(f"{ROLE_PREFIX}-*.toml")):
        if path.name not in roles and _is_generated(path):
            path.unlink()
            report("OK", "agents", f"removed {path.name} (no longer shipped)")

    state = {"plugin_root": str(PLUGIN_ROOT), "version": plugin_version(PLUGIN_ROOT), "tiers": tiers}
    (home / STATE_FILE).write_text(json.dumps(state, indent=2) + "\n")
    report("INFO", "next", "start a new Codex session; roles are loaded at session start")
    return report.finish()


def cmd_set_depth(args):
    home = codex_home(args.codex_home)
    config_path = home / "config.toml"
    report = Report()
    text = config_path.read_text(encoding="utf-8") if config_path.is_file() else ""
    current = max_depth(load_toml(config_path))
    if current is not None and current >= args.depth:
        report("OK", "max_depth", f"already {current} in {config_path}; unchanged")
        return report.finish()
    new = set_max_depth_text(text, args.depth)
    home.mkdir(parents=True, exist_ok=True)
    if config_path.is_file():
        stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        backup = config_path.with_name(f"config.toml.bak-gismo-{stamp}")
        shutil.copy2(config_path, backup)
        report("INFO", "backup", str(backup))
    config_path.write_text(new, encoding="utf-8")
    report("OK", "max_depth", f"{current if current is not None else 'unset'} -> {args.depth} in {config_path}")
    return report.finish()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("check", "install", "set-depth"):
        p = sub.add_parser(name)
        p.add_argument("--codex-home", help="Codex home (default: $CODEX_HOME or ~/.codex)")
        if name == "check":
            p.add_argument("--project", help="a G+Smo checkout whose .codex/config.toml to include")
        if name == "install":
            p.add_argument("--tier", action="append", metavar="TIER=MODEL",
                           help=f"override a tier mapping (defaults: {DEFAULT_TIERS})")
        if name == "set-depth":
            p.add_argument("--depth", type=int, default=REQUIRED_DEPTH)
    args = parser.parse_args(argv)
    try:
        return {"check": cmd_check, "install": cmd_install, "set-depth": cmd_set_depth}[args.command](args)
    except (SetupError, OSError) as error:
        print(f"FAIL {args.command}: {error}")
        print("STATUS: FAIL 1")
        return 2


if __name__ == "__main__":
    sys.exit(main())
